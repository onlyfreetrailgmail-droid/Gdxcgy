export const ensureIndexes = async (db) => {
  const unique = { unique: true };
  await Promise.all([
    db.collection('products').createIndex({ slug: 1 }, unique),
    db.collection('products').createIndex({ categorySlug: 1, active: 1 }),
    db.collection('orders').createIndex({ id: 1 }, unique),
    db.collection('orders').createIndex({ guestToken: 1 }, unique),
    db.collection('orders').createIndex({ userId: 1, createdAt: -1 }),
    db.collection('orders').createIndex({ razorpayOrderId: 1 }, { unique: true, partialFilterExpression: { razorpayOrderId: { $type: 'string' } } }),
    db.collection('orders').createIndex({ paymentReference: 1 }, { unique: true, partialFilterExpression: { paymentReference: { $type: 'string' } } }),
    db.collection('orders').createIndex({ balanceRazorpayOrderId: 1 }, { unique: true, partialFilterExpression: { balanceRazorpayOrderId: { $type: 'string' } } }),
    db.collection('orders').createIndex({ balancePaymentId: 1 }, { unique: true, partialFilterExpression: { balancePaymentId: { $type: 'string' } } }),
    db.collection('orders').createIndex({ paymentStatus: 1, balanceRequestedAt: 1 }),
    db.collection('users').createIndex({ email: 1 }, unique),
    db.collection('otps').createIndex({ expiresAt: 1 }, { expireAfterSeconds: 0 }),
    db.collection('otps').createIndex({ email: 1, createdAt: -1 }),
    db.collection('rate_limits').createIndex({ expiresAt: 1 }, { expireAfterSeconds: 0 }),
    db.collection('refresh_tokens').createIndex({ expiresAt: 1 }, { expireAfterSeconds: 0 }),
    db.collection('refresh_tokens').createIndex({ tokenHash: 1 }, unique),
    db.collection('webhook_events').createIndex({ eventId: 1 }, unique),
    db.collection('invoices').createIndex({ number: 1 }, unique),
    db.collection('invoices').createIndex({ orderId: 1, type: 1 }),
    db.collection('invoices').createIndex({ paymentId: 1 }, { unique: true, partialFilterExpression: { type: 'receipt' } }),
    db.collection('invoices').createIndex({ refundId: 1 }, { unique: true, partialFilterExpression: { type: 'credit_note' } }),
    db.collection('refunds').createIndex({ razorpayRefundId: 1 }, { unique: true, partialFilterExpression: { razorpayRefundId: { $type: 'string' } } }),
    db.collection('refunds').createIndex({ orderId: 1 }),
    db.collection('audit_logs').createIndex({ targetId: 1, at: -1 }),
    db.collection('shipments').createIndex({ awb: 1 }, unique),
    db.collection('shipments').createIndex({ orderId: 1 }),
    db.collection('email_queue').createIndex({ key: 1 }, unique),
    db.collection('tracking_events').createIndex({ eventId: 1 }, unique),
    db.collection('tracking_events').createIndex({ createdAt: -1 }),
    db.collection('email_queue').createIndex({ status: 1, nextAttemptAt: 1 }),
    db.collection('email_queue').createIndex({ providerId: 1 }),
    db.collection('email_prefs').createIndex({ email: 1 }, unique),
    db.collection('email_suppressions').createIndex({ email: 1 }, unique),
    db.collection('addresses').createIndex({ userId: 1 }),
    db.collection('wishlists').createIndex({ userId: 1 }, unique),
    db.collection('coupons').createIndex({ code: 1 }, unique),
    db.collection('reviews').createIndex({ userId: 1, productId: 1 }, unique),
    db.collection('reviews').createIndex({ productId: 1, status: 1, createdAt: -1 }),
    db.collection('enquiries').createIndex({ status: 1, createdAt: -1 }),
    db.collection('return_requests').createIndex({ orderId: 1, status: 1 }),
    db.collection('return_requests').createIndex({ status: 1, createdAt: -1 }),
    db.collection('review_uploads').createIndex({ publicId: 1 }, unique),
    db.collection('review_uploads').createIndex({ used: 1, createdAt: 1 }),
    db.collection('banners').createIndex({ active: 1, position: 1 }),
    db.collection('alerts').createIndex({ key: 1 }, unique),
    db.collection('payment_failures').createIndex({ at: 1 }, { expireAfterSeconds: 14 * 24 * 3600 }),
    db.collection('server_errors').createIndex({ at: 1 }, { expireAfterSeconds: 24 * 3600 }),
    db.collection('counters').createIndex({ _id: 1 })
  ]);
};
